function lang(l) {
  localStorage.setItem("gwaLang", l);
  document.documentElement.lang = l;
  document.querySelectorAll("[data-t]").forEach((e) => {
    if (t[l][e.dataset.t]) e.textContent = t[l][e.dataset.t];
  });
  document
    .querySelectorAll("[data-lang]")
    .forEach((b) => b.classList.toggle("active", b.dataset.lang === l));
}
document.addEventListener("DOMContentLoaded", () => {
  lang(localStorage.getItem("gwaLang") || "sv");
  document
    .querySelectorAll("[data-lang]")
    .forEach((b) => (b.onclick = () => lang(b.dataset.lang)));
  let m = document.querySelector(".menu"),
    n = document.querySelector(".nav-links");
  m.onclick = () => n.classList.toggle("open");
});
